LEGACY_USERNAME_MAP = {
    "admin.kaushal-patel": "admin.kaushal",
    "adamin.kaushal": "admin.kaushal",
}


class Command(BaseCommand):
    help = "Create or update the requested local MediMart role accounts without deleting existing data."

    def add_arguments(self, parser):
        parser.add_argument(
            "--password",
            default=DEFAULT_PASSWORD,
            help="Password for newly created accounts. Existing account passwords are not changed.",
        )

    @staticmethod
    def username_for(role, name):
        if role == UserProfile.Role.ADMIN:
            return "admin.kaushal"
        return f"{slugify(role)}.{slugify(name)}"

    @staticmethod
    def email_for(username):
        return f"{username}@gmail.com"

    def write_credentials_file(self, password):
        role_labels = dict(UserProfile.Role.choices)
        lines = [
            "# MediMart Role Account Credentials",
            "",
            "Generated by `python manage.py seed_role_accounts` for local development.",
            "",
            "> These are development accounts. Change every password before production and never share this file publicly.",
            "",
            f"New-account password used by this seed run: `{password}`",
            "",
            "Existing account passwords are not changed when the seeder is run again.",
            "",
        ]
        for role, names in ROLE_NAMES.items():
            lines.extend([
                f"## {role_labels.get(role, role)} ({len(names)})",
                "",
                "| Name | Username | Email | Role |",
                "| --- | --- | --- | --- |",
            ])
            for name in names:
                username = self.username_for(role, name)
                lines.append(
                    f"| {name} | `{username}` | `{self.email_for(username)}` | `{role}` |"
                )
            lines.append("")

        target = Path(settings.BASE_DIR) / "ROLE_ACCOUNT_CREDENTIALS.md"
        target.write_text("\n".join(lines), encoding="utf-8")

    @transaction.atomic
    def handle(self, *args, **options):
        User = get_user_model()
        password = options["password"]
        created_count = 0
        updated_count = 0
        phone_number = 9000000000

        for legacy_username, new_username in LEGACY_USERNAME_MAP.items():
            legacy_user = User.objects.filter(username=legacy_username).first()
            if legacy_user and not User.objects.filter(username=new_username).exists():
                legacy_user.username = new_username
                legacy_user.save(update_fields=["username"])

        for role, names in ROLE_NAMES.items():
            for name in names:
                username = self.username_for(role, name)
                first_name, *last_names = name.split()
                last_name = " ".join(last_names)
                user, created = User.objects.get_or_create(
                    username=username,
                    defaults={
                        "email": self.email_for(username),
                        "first_name": first_name,
                        "last_name": last_name,
                        "is_active": True,
                    },
                )
                if created:
                    user.set_password(password)
                    user.save(update_fields=["password"])
                    created_count += 1
                else:
                    user.email = self.email_for(username)
                    user.first_name = first_name
                    user.last_name = last_name
                    user.is_active = True
                    user.save(update_fields=["email", "first_name", "last_name", "is_active"])
                    updated_count += 1

                if role == UserProfile.Role.ADMIN:
                    user.is_staff = True
                    user.is_superuser = True
                    user.save(update_fields=["is_staff", "is_superuser"])

                UserProfile.objects.update_or_create(
                    user=user,
                    defaults={
                        "role": role,
                        "phone_number": str(phone_number),
                    },
                )
                phone_number += 1

        total = sum(len(names) for names in ROLE_NAMES.values())
        self.write_credentials_file(password)
        self.stdout.write(self.style.SUCCESS(
            f"Role accounts ready: {total} requested, {created_count} created, {updated_count} reused/updated."
        ))
        self.stdout.write(f"New account password: {password}")
        self.stdout.write("Usernames use the pattern: <role>.<first>.<last>")
        self.stdout.write("Admin username: admin.kaushal")
